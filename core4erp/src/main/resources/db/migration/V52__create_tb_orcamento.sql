-- V52: Orçamento mensal por categoria + permissões ORCAMENTO_VISUALIZAR / ORCAMENTO_EDITAR.
--
-- Um orçamento é um limite MENSAL recorrente para uma categoria principal (raiz). O gasto do mês é
-- calculado em tempo de leitura (nunca persistido — CLAUDE.md §16) com roll-up das subcategorias.
-- Soft delete: excluir = ativo=false (histórico preservado); só pode existir UM orçamento ativo por
-- categoria em cada empresa (índice único parcial).

CREATE TABLE tb_orcamento (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_by         VARCHAR(100),
    created_date       TIMESTAMP(6),
    last_modified_by   VARCHAR(100),
    last_modified_date TIMESTAMP(6),
    empresa_id         BIGINT         NOT NULL,
    categoria_id       BIGINT         NOT NULL,
    usuario_id         BIGINT         NOT NULL,
    valor_limite       NUMERIC(15, 2) NOT NULL,
    ativo              BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT tb_orcamento_pkey PRIMARY KEY (id),
    CONSTRAINT ck_orcamento_valor_limite_positivo CHECK (valor_limite > 0),
    CONSTRAINT fk_orcamento_empresa   FOREIGN KEY (empresa_id)   REFERENCES tb_empresa (id),
    CONSTRAINT fk_orcamento_categoria FOREIGN KEY (categoria_id) REFERENCES tb_categoria (id),
    CONSTRAINT fk_orcamento_usuario   FOREIGN KEY (usuario_id)   REFERENCES tb_usuario (id)
);

CREATE INDEX idx_orcamento_empresa   ON tb_orcamento (empresa_id);
CREATE INDEX idx_orcamento_categoria ON tb_orcamento (categoria_id);

-- Um orçamento ativo por (empresa, categoria); inativos (excluídos) não bloqueiam recriar.
CREATE UNIQUE INDEX uq_orcamento_empresa_categoria_ativo
    ON tb_orcamento (empresa_id, categoria_id)
    WHERE ativo;

-- ── Permissões ───────────────────────────────────────────────────────────────

INSERT INTO tb_permissao (codigo, modulo, acao, descricao) VALUES
    ('ORCAMENTO_VISUALIZAR', 'ORCAMENTO', 'VISUALIZAR', 'Ver orçamento mensal por categoria'),
    ('ORCAMENTO_EDITAR',     'ORCAMENTO', 'EDITAR',     'Criar, alterar e remover limites do orçamento');

-- ORCAMENTO_VISUALIZAR: todos os perfis do sistema (empresa_id IS NULL — perfis customizados das
-- empresas são geridos por elas; nomes de perfis do sistema são reservados).
INSERT INTO tb_perfil_permissao (perfil_id, permissao_id)
SELECT p.id, pm.id
FROM tb_perfil_acesso p CROSS JOIN tb_permissao pm
WHERE pm.codigo = 'ORCAMENTO_VISUALIZAR'
  AND p.empresa_id IS NULL
  AND p.nome IN ('PROPRIETARIO','ADMIN','FINANCEIRO','OPERADOR','VISUALIZADOR');

-- ORCAMENTO_EDITAR: PROPRIETARIO, ADMIN e FINANCEIRO
INSERT INTO tb_perfil_permissao (perfil_id, permissao_id)
SELECT p.id, pm.id
FROM tb_perfil_acesso p CROSS JOIN tb_permissao pm
WHERE pm.codigo = 'ORCAMENTO_EDITAR'
  AND p.empresa_id IS NULL
  AND p.nome IN ('PROPRIETARIO','ADMIN','FINANCEIRO');
